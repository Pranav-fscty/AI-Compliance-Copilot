# Public API
# ---------------------------------------------------------------------------


def evaluate_single(q: dict, llm: ChatOllama) -> EvalResult:
    """Evaluates a single question dict against the RAG chain and judge LLM.

    Steps:
      1. Calls ``rag_chain.ask(question, law_type)`` to obtain an answer and
         citations.
      2. Checks whether ``q["expected_section"]`` appears in any citation.
      3. Calls the judge LLM with ``JUDGE_PROMPT_TEMPLATE`` to score the answer.
      4. Returns a fully populated ``EvalResult``.

    Args:
        q: A question dict with keys ``"question"``, ``"expected_section"``,
           and ``"law_type"``.
        llm: A ``ChatOllama`` instance used as the LLM-as-judge.

    Returns:
        EvalResult: The fully populated evaluation result for this question.
    """
    question: str = q["question"]
    expected_section: str = q["expected_section"]
    law_type: str = q["law_type"]

    logger.info(
        "Evaluating — law_type=%s  expected=%r  question=%r",
        law_type,
        expected_section,
        question[:80],
    )

    # Step 1 — RAG chain inference
    try:
        ask_result = rag_chain.ask(question, law_type)
    except Exception as exc:  # noqa: BLE001
        logger.error(
            "rag_chain.ask() raised %s for question %r: %s",
            type(exc).__name__,
            question[:80],
            exc,
        )
        # Return a zero-scored result so the run continues
        return EvalResult(
            question=question,
            law_type=law_type,
            expected_section=expected_section,
            retrieved_sections=[],
            retrieval_hit=False,
            answer="",
            judge_score=0,
            judge_reason="rag_chain_error",
        )

    answer: str = ask_result["answer"]
    citations: list[dict] = ask_result["citations"]
    retrieved_sections: list[str] = [c.get("section", "") for c in citations]

    # Step 2 — Retrieval hit check
    retrieval_hit = any(
        q["expected_section"].lower() in c["section"].lower() or
        c["section"].lower() in q["expected_section"].lower()
        for c in citations
    )

    logger.debug(
        "retrieval_hit=%s  retrieved_sections=%r",
        retrieval_hit,
        retrieved_sections,
    )

    # Step 3 — LLM-as-judge scoring
    judge_score, judge_reason = _call_judge(
        question=question,
        expected_section=expected_section,
        answer=answer,
        llm=llm,
    )

    logger.info(
        "Result — retrieval_hit=%s  judge_score=%d  reason=%r",
        retrieval_hit,
        judge_score,
        judge_reason[:120],
    )

    return EvalResult(
        question=question,
        law_type=law_type,
        expected_section=expected_section,
        retrieved_sections=retrieved_sections,
        retrieval_hit=retrieval_hit,
        answer=answer,
        judge_score=judge_score,
        judge_reason=judge_reason,
    )


def run_eval(eval_path: str = "eval/questions.json") -> dict:
    """Runs the full evaluation pipeline over all questions in ``eval_path``.

    Loads the question set, evaluates each question via ``evaluate_single``,
    aggregates metrics, logs a per-question result row, and logs a final
    summary. Never raises on individual question failures — bad rows are
    counted with score 0 and retrieval_hit=False.

    Args:
        eval_path: Path (relative or absolute) to the JSON file containing
            the evaluation questions. Defaults to ``"eval/questions.json"``.

    Returns:
        dict: Aggregated metrics with keys:
            - ``"retrieval_accuracy"`` (float): fraction of questions where
              the expected section was found in citations.
            - ``"avg_judge_score"`` (float): mean judge score across all
              questions (0-scored rows lower this average).
            - ``"pct_acceptable"`` (float): fraction of questions where
              ``judge_score >= MIN_ACCEPTABLE_SCORE``.

    Raises:
        FileNotFoundError: If ``eval_path`` does not exist.
        ValueError: If ``eval_path`` contains invalid JSON or is not a list.
    """
    path = Path(eval_path)
    if not path.exists():
        raise FileNotFoundError(
            f"Eval file not found: {path.resolve()}. "
            "Create eval/questions.json before running the evaluation."
        )

    logger.info("Loading evaluation questions from: %s", path.resolve())

    with path.open("r", encoding="utf-8") as fh:
        questions: list[dict] = json.load(fh)

    if not isinstance(questions, list):
        raise ValueError(
            f"eval/questions.json must contain a JSON array, got: {type(questions)}"
        )

    total: int = len(questions)
    logger.info("Loaded %d evaluation questions.", total)

    if total == 0:
        logger.warning("No questions found in %s — returning zero metrics.", eval_path)
        return {
            "retrieval_accuracy": 0.0,
            "avg_judge_score": 0.0,
            "pct_acceptable": 0.0,
        }

    # Instantiate a single judge LLM using Ollama

    judge_llm = ChatOllama(
        model="llama3.1",
        temperature=0,
    )

    results: list[EvalResult] = []

    for idx, q in enumerate(questions, start=1):
        logger.info("─── Question %d / %d ───", idx, total)
        result = evaluate_single(q, judge_llm)
        results.append(result)

        # Per-question log row
        logger.info(
            "[%d/%d] %-70s | hit=%-5s | score=%d | %s",
            idx,
            total,
            result["question"][:70],
            result["retrieval_hit"],
            result["judge_score"],
            result["judge_reason"][:80],
        )

    # -----------------------------------------------------------------------
    # Aggregate metrics
    # -----------------------------------------------------------------------
    retrieval_hits: list[bool] = [r["retrieval_hit"] for r in results]
    judge_scores: list[int] = [r["judge_score"] for r in results]

    retrieval_accuracy: float = sum(retrieval_hits) / total
    avg_judge_score: float = statistics.mean(judge_scores)
    pct_acceptable: float = sum(
        1 for s in judge_scores if s >= MIN_ACCEPTABLE_SCORE
    ) / total

    summary: dict = {
        "retrieval_accuracy": round(retrieval_accuracy, 4),
        "avg_judge_score": round(avg_judge_score, 4),
        "pct_acceptable": round(pct_acceptable, 4),
    }

    logger.info(
        "═══ EVAL SUMMARY ═══  questions=%d  retrieval_accuracy=%.2f%%  "
        "avg_judge_score=%.2f  pct_acceptable=%.2f%%",
        total,
        retrieval_accuracy * 100,
        avg_judge_score,
        pct_acceptable * 100,
    )

    return summary


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


def main() -> None:
    """Runs the evaluation pipeline and prints the aggregated summary dict.

    Configures a basic logging format if no handlers are already attached,
    then delegates to ``run_eval()`` and prints the resulting metrics dict
    to stdout for easy inspection.
    """
    import sys  # noqa: PLC0415

    # Ensure at least a basic handler is present when run as __main__
    if not logging.root.handlers:
        logging.basicConfig(
            level=logging.INFO,
            format="%(asctime)s %(levelname)-8s %(name)s — %(message)s",
            stream=sys.stdout,
        )

    summary = run_eval()
    print("\n" + "=" * 60)
    print("EVALUATION COMPLETE")
    print("=" * 60)
    print(json.dumps(summary, indent=2))
    print("=" * 60)


if __name__ == "__main__":
    main()
