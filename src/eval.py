"""Evaluation pipeline for the compliance-copilot RAG system.

Measures two key metrics against a hand-curated question set stored in
``eval/questions.json``:

  - **retrieval_accuracy**: fraction of questions for which the expected
    legal section appeared in at least one citation returned by the RAG chain.
  - **avg_judge_score**: mean LLM-as-judge score (1–5) across all questions,
    reflecting factual accuracy and completeness of the generated answer.
  - **pct_acceptable**: fraction of questions whose judge score meets or
    exceeds ``MIN_ACCEPTABLE_SCORE``.

Usage::

    python -m src.eval

The module reads ``eval/questions.json`` and calls ``src.rag_chain.ask`` for
each question, so the Chroma vector store must be built before running this.
"""

from __future__ import annotations

import json
import logging
import statistics
from pathlib import Path
from typing import TypedDict

from langchain_ollama import ChatOllama
from langchain.schema import HumanMessage

import src.rag_chain as rag_chain

# ---------------------------------------------------------------------------
# Module logger
# ---------------------------------------------------------------------------

logger: logging.Logger = logging.getLogger("compliance-copilot.eval")

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

MIN_ACCEPTABLE_SCORE: int = 3

JUDGE_PROMPT_TEMPLATE: str = """\
You are an impartial legal-QA evaluator. Your task is to score an AI-generated \
answer to a legal compliance question on a scale of 1 to 5.

Scoring rubric:
  5 — Fully accurate and complete. The answer directly addresses the question, \
references the correct legal section, and contains no material errors.
  4 — Mostly accurate. Minor omissions or slight imprecision, but the core \
answer is correct.
  3 — Partially correct. The answer is relevant but misses important details \
or contains a non-critical inaccuracy.
  2 — Mostly incorrect or incomplete. The answer may be tangentially related \
but fails to address the question properly.
  1 — Completely wrong, irrelevant, or a refusal to answer.

---
QUESTION:
{question}

EXPECTED SECTION (ground truth reference from source documents):
{expected_section}

GENERATED ANSWER:
{answer}
---

Respond with ONLY a JSON object — no markdown fences, no extra text:
{{"score": <integer 1-5>, "reason": "<one-sentence explanation>"}}
"""

# ---------------------------------------------------------------------------
# TypedDicts
# ---------------------------------------------------------------------------


class EvalResult(TypedDict):
    """Structured result for a single evaluated question.

    Attributes:
        question: The original natural-language question.
        law_type: The law domain filter used when calling the RAG chain.
        expected_section: The ground-truth section the answer should cite.
        retrieved_sections: List of section strings returned in citations.
        retrieval_hit: True if ``expected_section`` appeared in any citation.
        answer: The answer text generated by the RAG chain.
        judge_score: LLM-as-judge integer score in [1, 5] (0 on parse error).
        judge_reason: One-sentence justification from the judge LLM.
    """

    question: str
    law_type: str
    expected_section: str
    retrieved_sections: list[str]
    retrieval_hit: bool
    answer: str
    judge_score: int
    judge_reason: str


# ---------------------------------------------------------------------------
# Core evaluation helpers
# ---------------------------------------------------------------------------


def _check_retrieval_hit(expected_section: str, citations: list[dict]) -> bool:
    """Returns True if ``expected_section`` appears in any citation's section field.

    Matching is case-insensitive and checks for substring containment so that
    an expected value like ``"Section 73"`` matches a citation section stored
    as ``"Section 73 – Determination of tax"``.

    Args:
        expected_section: The ground-truth section identifier from the eval set.
        citations: List of ``Citation`` dicts (``{"source": str, "section": str}``).

    Returns:
        bool: True if any citation section contains ``expected_section``.
    """
    needle = expected_section.strip().lower()
    for citation in citations:
        haystack = citation.get("section", "").strip().lower()
        if needle in haystack or haystack in needle:
            return True
    return False


def _call_judge(
    question: str,
    expected_section: str,
    answer: str,
    llm: ChatOllama,
) -> tuple[int, str]:
    """Calls the judge LLM and returns a (score, reason) pair.

    The LLM is instructed to respond with a JSON object
    ``{"score": int, "reason": str}``. Malformed or non-JSON responses are
    caught and converted to a fallback ``(0, "parse_error")`` tuple so the
    pipeline never crashes on bad LLM output.

    Args:
        question: The original compliance question.
        expected_section: The ground-truth section identifier.
        answer: The RAG-generated answer to evaluate.
        llm: A ``ChatOllama`` instance used as the judge.   

    Returns:
        tuple[int, str]: ``(judge_score, judge_reason)`` where ``judge_score``
            is 0 if the response could not be parsed.
    """
    prompt_text = JUDGE_PROMPT_TEMPLATE.format(
        question=question,
        expected_section=expected_section,
        answer=answer,
    )

    logger.debug("Calling judge LLM for question: %r", question[:60])

    try:
        response = llm.invoke([HumanMessage(content=prompt_text)])
        raw: str = response.content.strip()

        # Strip optional markdown code fences (```json ... ```)
        if raw.startswith("```"):
            lines = raw.splitlines()
            raw = "\n".join(
                line for line in lines if not line.strip().startswith("```")
            ).strip()

        parsed: dict = json.loads(raw)
        score: int = int(parsed["score"])
        reason: str = str(parsed.get("reason", ""))

        if score < 1 or score > 5:
            logger.warning(
                "Judge returned out-of-range score %d; clamping to [1,5].", score
            )
            score = max(1, min(5, score))

        return score, reason

    except (json.JSONDecodeError, KeyError, ValueError, TypeError) as exc:
        logger.warning(
            "Failed to parse judge response for question %r — %s: %s. "
            "Falling back to score=0.",
            question[:60],
            type(exc).__name__,
            exc,
        )
        return 0, "parse_error"

    except Exception as exc:  # noqa: BLE001
        logger.error(
            "Unexpected error during judge call for question %r — %s: %s. "
            "Falling back to score=0.",
            question[:60],
            type(exc).__name__,
            exc,
        )
        return 0, "parse_error"


